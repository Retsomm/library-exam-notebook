import {test,expect} from '@playwright/test';
for(const width of [390,1440])test(`idiom dictionary and shared answers at ${width}px`,async({page})=>{
 await page.setViewportSize({width,height:900});
 await page.goto('/demo/');
 await page.getByRole('navigation',{name:'主要導覽'}).getByRole('button',{name:'重點整理',exact:true}).click();
 await page.getByRole('button',{name:/歷屆成語庫/}).click();
 await expect(page.locator('.idiom-card')).toHaveCount(20);
 const first=await page.locator('.idiom-card h3').first().textContent();
 await page.getByRole('button',{name:'下一頁',exact:true}).click();
 await expect(page.locator('.idiom-card h3').first()).not.toHaveText(first!);
 const search=page.getByRole('searchbox',{name:'搜尋成語'});
 await search.fill('別無長物');
 const card=page.getByRole('article',{name:'別無長物',exact:true});
 await expect(card).toBeVisible();
 await expect(card.getByText(/不是沒有專長/)).toBeVisible();
 await expect(card.getByText('他的小屋只有書桌和床，幾乎別無長物。',{exact:true})).toBeVisible();
 await page.getByRole('combobox',{name:'題目年度'}).selectOption('115');
 await card.getByText(/查看歷屆出處/).click();
 await expect(card.locator('.note-source')).toHaveCount(1);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
 await card.getByRole('button',{name:'查看 115 年第 4 題原題解析'}).click();
 await expect(page.getByRole('dialog')).toBeVisible();
 await page.getByRole('button',{name:'關閉解析',exact:true}).click();
 await card.getByRole('button',{name:'練習這一題',exact:true}).click();
 await page.locator('.answer-list .option').first().click();
 await page.getByRole('button',{name:'確認答案',exact:true}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await page.getByRole('button',{name:'查看解析',exact:true}).click();
 await expect(page.getByRole('dialog')).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
});
